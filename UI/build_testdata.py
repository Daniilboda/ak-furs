def _chat(chat_id: str, *lines: str) -> bytes:
    header = f"Чат {chat_id} | клиент CL-900 | заказ A-9001 | менеджер Вероника Белова"
    text = header + "\n" + "\n".join(lines) + "\n"
    return ("\ufeff" + text).encode("utf-8")


